"""엔티티별 정규식 + L3 담당 형식 제외 패턴. 데이터라 파일을 분리한다.

형식만으로는 이 4종을 서로 구분할 수 없다(자릿수가 겹친다). 형식은 후보를
좁히는 1차 필터일 뿐이고, 최종 판별은 ``recognizers.py`` 가 앵커로 한다.
"""

from __future__ import annotations

import re

# 경계는 \b 대신 ASCII 영숫자 기준 lookaround로 잡는다. Python re는 한글도
# \w로 쳐서, "P220194827163으로"처럼 조사가 붙으면 \b가 숫자-한글 경계에서
# 성립하지 않아 후보 자체가 안 생긴다. ASCII만 "경계 아님"으로 치면 해결된다.
_L = r"(?<![A-Za-z0-9])"  # 왼쪽 경계
_R = r"(?![A-Za-z0-9])"  # 오른쪽 경계

# ORDER_ID는 숫자로 시작해야 한다 — 문자 접두어를 허용하면 CUSTOMER_ID
# (영문 0~4자+숫자)와 형식이 겹쳐 어느 쪽으로 판별할지 애매해진다. 그 대가로
# "ORD-88192-KR" 같은 완전 문자 접두어는 아예 미탐지되고, "B2B-ORD-20260910
# -8841"처럼 하이픈으로 이어진 접두어는 뒤쪽 숫자 부분("20260910-8841")만
# 부분 매치된다. 둘 다 설계 범위 밖 — 접두어까지 넓히려면 CUSTOMER_ID와의
# 충돌부터 재설계해야 해서 W7 실사용 빈도 확인 후 재판단.
PATTERNS: dict[str, re.Pattern[str]] = {
    "CUSTOMS_CLEARANCE_ID": re.compile(_L + r"[Pp]\d{12}" + _R),
    "ORDER_ID": re.compile(_L + r"\d{6,20}(?:-\d{1,10})?" + _R),
    "TRACKING_NUMBER": re.compile(_L + r"[A-Za-z0-9]{8,20}" + _R),
    "CUSTOMER_ID": re.compile(_L + r"[A-Za-z]{0,4}[-_]?\d{4,15}" + _R),
}

# 다른 확정 타입(L3 담당)과 형식이 겹치는 후보는 우리 것이 아니다. 전화번호는
# 정규식 대신 phonenumbers로 판별한다(recognizers.py의 _is_phone_number) —
# 자릿수만으로는 우리 ID들과 안전하게 못 갈라서다. 생년월일(YYMMDD) 검증까지
# 해서 "999999-1234567"처럼 월/일이 무효한 건 주민등록번호가 아니라고 정확히
# 판별한다.
EXCLUDE_PATTERNS: list[re.Pattern[str]] = [
    # 주민등록번호(RRN): YYMMDD + 성별코드 1~4
    re.compile(r"(?<!\d)\d{2}(0[1-9]|1[0-2])(0[1-9]|[12]\d|3[01])(-?)[1-4]\d{6}(?!\d)"),
    # 외국인등록번호(FRN): RRN과 동일 자리수, 성별코드만 5~8
    re.compile(r"(?<!\d)\d{2}(0[1-9]|1[0-2])(0[1-9]|[12]\d|3[01])(-?)[5-8]\d{6}(?!\d)"),
    # 사업자등록번호: 하이픈 포함/미포함 둘 다. 미포함 10자리는 임의의 숫자와
    # 구분이 안 돼 recall이 깎이지만 L3가 확정한 실제 형식이라 그대로 쓴다.
    re.compile(r"(?<!\d)\d{3}-\d{2}-\d{5}(?!\d)|(?<!\d)\d{10}(?!\d)"),
    # 이메일: L3 담당 타입이 아니라 순수 오탐 방지용. ID 패턴들의 ASCII 경계
    # 규칙이 '@'/'.'/'-'를 전부 비영숫자로 쳐서, 이메일 안의 라벨 하나하나
    # (로컬파트, 도메인, TLD)가 독립된 후보로 오탐될 수 있다(예:
    # "sjpark@corp-solution.co.kr"의 "solution"이 TRACKING_NUMBER와 우연히
    # 일치). TLD를 {2,}로 열어둔 건 ".solutions"처럼 긴 TLD도 도메인 전체를
    # 한 번에 삼켜야 라벨이 안 쪼개지기 때문이다.
    re.compile(r"(?<![A-Za-z0-9])[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}(?![A-Za-z0-9])"),
]

# ORDER_ID 전용: 순수 날짜(YYYYMMDD 등, 뒤에 -숫자 없음)는 배제한다.
# "20260830-1234567"처럼 하이픈+숫자가 붙으면 주문번호로 본다.
ORDER_ID_DATE_EXCLUDE: re.Pattern[str] = re.compile(
    _L + r"\d{4}[-.]?\d{2}[-.]?\d{2}" + _R + r"(?!-\d)"
)

# ACCOUNT_NUMBER: 하이픈 포함 형식만. 은행마다 그룹 자릿수가 달라(국민
# 6-2-6, 카카오뱅크 4-2-7) 마지막 그룹을 {2,7}까지 넓혔다.
#
# 하이픈 없는 순수 숫자는 제외 — 사업자등록번호(\d{10}, EXCLUDE_PATTERNS
# 참고)와 자릿수가 겹쳐 오탐 위험이 크다.
# TODO: 하이픈 없는 사업자번호 실사용 빈도가 확인되면 하이픈 없는 계좌번호
# 형식 추가 여부 결정.
ACCOUNT_NUMBER_3GRP: re.Pattern[str] = re.compile(_L + r"\d{2,7}-\d{2,7}-\d{2,7}" + _R)
ACCOUNT_NUMBER_2GRP: re.Pattern[str] = re.compile(_L + r"\d{3,6}-\d{6,8}" + _R)

# 은행별 3그룹 자릿수 조합 — confidence 가산 참고용이지 확정 판정이 아니다.
# 표에 없는 조합이거나 은행명이 안 잡혀도 emit 여부(그룹 수·앵커 필수)에는
# 영향 없다. recognizers.py의 find_account_number 참고.
BANK_DIGIT_GROUPS: dict[str, tuple[tuple[int, int, int], ...]] = {
    "국민": ((3, 2, 4), (6, 2, 5)),
    "기업": ((3, 6, 4),),
    "농협": ((3, 4, 4), (3, 2, 6)),
    "신한": ((3, 2, 6),),
    "우리": ((4, 4, 5),),
    "하나": ((3, 6, 4),),
    "SC제일": ((3, 2, 4), (3, 6, 2)),
    "씨티": ((3, 6, 2),),
    "대구": ((3, 2, 5), (3, 6, 2)),
    "부산": ((3, 3, 4), (3, 2, 6)),
    "광주": ((3, 4, 4),),
    "경남": ((3, 4, 4),),
    "전북": ((3, 2, 6),),
    "제주": ((2, 2, 5),),
    "수협": ((3, 2, 6),),
    "우체국": ((6, 2, 6),),
    "새마을금고": ((4, 4, 4),),
}

# 주소 3종은 왼쪽 경계에 한글 음절도 막는다(`_L`은 ASCII만) — "우논현로"를
# "논현로"로 잘라 먹으면 안 되기 때문이다.
_KL = r"(?<![A-Za-z0-9가-힣])"  # 왼쪽 경계 — 한글 포함

# ADDRESS_ROAD: 도로명 + 건물번호. 건물번호가 정규식에 필수라("종로에서"처럼
# 번호 없이 도로명만 오면 매치 안 됨) 그 자체가 자격 조건이라 앵커가 필요
# 없다. confidence는 형식 매치만으로 고정 0.5.
#
# `(?:\d{1,3}길)?`은 지선도로명("OO로7길") 대응용 — 없으면 "성수이로7길
# 12번"에서 "7"을 건물번호로 오인해 "길"과 실제 번호 "12"를 잃는다.
ADDRESS_ROAD_PATTERN: re.Pattern[str] = re.compile(
    _KL
    + r"[가-힣]{2,10}(?:대로|로)(?:\d{1,3}길)?\s?\d{1,5}(?:-\d{1,5})?"
    + _R
    + r"|"
    + _KL
    + r"[가-힣]{2,10}길\s?\d{1,5}(?:-\d{1,5})?"
    + _R
)

# ADDRESS_LOT: 지번. "번지"/"산" 리터럴 자체가 자격 조건이라 순수 숫자-숫자는
# 안 걸린다(ORDER_ID 등과 형식 충돌 없음). confidence 고정 0.7.
ADDRESS_LOT_PATTERN: re.Pattern[str] = re.compile(
    _L + r"\d{1,4}(?:-\d{1,4})?\s?번지" + _R + r"|" + _KL + r"산\s?\d{1,4}(?:-\d{1,4})?" + _R
)

# ADDRESS_DETAIL: 동/호/층 리터럴 자체가 자격 조건. 세 갈래(동+호/호만/층만)로
# 오탐 위험이 달라 named group으로 구분해 confidence를 나눈다(find_address_detail
# 참고). 하나의 패턴으로 합친 건 겹침 방지 로직을 또 만들지 않기 위해서다.
ADDRESS_DETAIL_PATTERN: re.Pattern[str] = re.compile(
    _KL
    + r"(?P<dongho>\d{1,4}동\s?\d{1,5}호)"
    + _R
    + r"|"
    + _KL
    + r"(?P<ho>\d{1,5}호)"
    + _R
    + r"|"
    + _KL
    + r"(?P<floor>(?:지하)?\d{1,3}층)"
    + _R
)
