"""엔티티별 정규식 + L3 담당 형식 제외 패턴. 데이터라 파일을 분리한다.

형식만으로는 이 4종을 서로 구분할 수 없다(자릿수가 겹친다). 형식은 후보를
좁히는 1차 필터일 뿐이고, 최종 판별은 ``recognizers.py`` 가 앵커로 한다.
"""

from __future__ import annotations

import re

# 경계는 \b가 아니라 ASCII 영숫자 기준 lookaround로 잡는다. Python re는 유니코드
# 기본이라 한글 음절도 \w로 쳐서, "P220194827163으로"처럼 조사가 공백 없이 바로
# 붙으면(한국어 CS 문장에서 일상적) \b가 숫자-한글 경계에서 성립하지 않아 후보
# 자체가 안 생긴다(2026-09-11 실측으로 확인). ASCII만 "경계 아님"으로 치면 한글은
# 항상 경계로 인정돼 이 문제가 없다.
_L = r"(?<![A-Za-z0-9])"  # 왼쪽 경계
_R = r"(?![A-Za-z0-9])"  # 오른쪽 경계

PATTERNS: dict[str, re.Pattern[str]] = {
    "CUSTOMS_CLEARANCE_ID": re.compile(_L + r"[Pp]\d{12}" + _R),
    "ORDER_ID": re.compile(_L + r"\d{6,20}(?:-\d{1,10})?" + _R),
    "TRACKING_NUMBER": re.compile(_L + r"[A-Za-z0-9]{8,20}" + _R),
    "CUSTOMER_ID": re.compile(_L + r"[A-Za-z]{0,4}[-_]?\d{4,15}" + _R),
}

# 다른 확정 타입(L3 담당)과 형식이 겹치는 후보는 우리 것이 아니다.
# 정민우(L3) 회신 반영(2026-09-11) — 아래 3개는 L3 실제 구현과 대조한 정규식.
# 전화번호는 정규식이 아니라 phonenumbers 라이브러리로 판별한다(L3와 동일 방식,
# recognizers.py의 _is_phone_number). 자릿수만으로는 우리 ID들과 안전하게 못 갈라서다.
#
# 생년월일(YYMMDD) 검증까지 하는 게 초안보다 정확하다 — "999999-1234567"처럼
# 월/일이 무효면 주민등록번호가 아니라고 정확히 판별한다(초안은 자릿수만 봤음).
EXCLUDE_PATTERNS: list[re.Pattern[str]] = [
    # 주민등록번호(RRN): YYMMDD + 성별코드 1~4
    re.compile(r"(?<!\d)\d{2}(0[1-9]|1[0-2])(0[1-9]|[12]\d|3[01])(-?)[1-4]\d{6}(?!\d)"),
    # 외국인등록번호(FRN): RRN과 동일 자리수, 성별코드만 5~8
    re.compile(r"(?<!\d)\d{2}(0[1-9]|1[0-2])(0[1-9]|[12]\d|3[01])(-?)[5-8]\d{6}(?!\d)"),
    # 사업자등록번호: 하이픈 포함(123-45-67890) / 미포함(10자리 연속) 둘 다.
    # 미포함 형태는 임의의 10자리 숫자와 구분이 안 된다 — 10자리 송장번호 등과
    # 겹치면 우리 recall이 깎이지만, L3가 확정한 실제 형식이라 그대로 반영한다.
    re.compile(r"(?<!\d)\d{3}-\d{2}-\d{5}(?!\d)|(?<!\d)\d{10}(?!\d)"),
]

# ORDER_ID 전용: 순수 날짜(YYYYMMDD, YYYY-MM-DD 등, 뒤에 -숫자 없음)는 배제.
# "20260830-1234567" 처럼 뒤에 하이픈+숫자가 붙으면 주문번호로 본다.
# recognizers.py에서 격리된 candidate 문자열(match.group())에만 돌리므로 원문의
# 앞뒤 문맥과는 무관하다 — 그래도 PATTERNS와 경계 기준을 통일해둔다.
ORDER_ID_DATE_EXCLUDE: re.Pattern[str] = re.compile(
    _L + r"\d{4}[-.]?\d{2}[-.]?\d{2}" + _R + r"(?!-\d)"
)

# ACCOUNT_NUMBER: 하이픈 포함 형식만(이번 범위). 은행마다 그룹 자릿수가 다르다
# (국민 123456-01-987654 = 6-2-6, 카카오뱅크 3333-01-9872112 = 4-2-7).
# 초안 지시서는 3그룹 각 자리를 {2,6}으로 줬는데, 카카오뱅크 실사용 예시
# (마지막 그룹 7자리)가 그 폭으로 안 잡혀서 {2,7}로 넓혔다 — 그 예시가 회귀
# 테스트로 남아 있어서 좁히면 바로 깨진다.
#
# 하이픈 없는 순수 숫자 형식은 이번 범위 제외. 사업자등록번호(하이픈 없음,
# \d{10}, L3 확정, EXCLUDE_PATTERNS 참고)와 자릿수가 겹쳐 오탐 위험이 크다.
# TODO: 정민우(L3) 회신 대기 — 하이픈 없는 사업자번호 실사용 빈도 확인되면
# 하이픈 없는 계좌번호 형식 추가 여부 결정.
ACCOUNT_NUMBER_3GRP: re.Pattern[str] = re.compile(_L + r"\d{2,7}-\d{2,7}-\d{2,7}" + _R)
ACCOUNT_NUMBER_2GRP: re.Pattern[str] = re.compile(_L + r"\d{3,6}-\d{6,8}" + _R)

# ADDRESS_ROAD/LOT/DETAIL: 왼쪽 경계에 한글 음절도 추가로 막는다(`_L`은 ASCII만).
# 도로명·지번·상세주소는 한글 단어 중간에서 잘못 끊기면 안 된다 — 예를 들어
# "우논현로" 처럼 앞에 다른 한글이 더 붙어 있는 걸 "논현로"로 잘라 먹으면 안 된다.
_KL = r"(?<![A-Za-z0-9가-힣])"  # 왼쪽 경계 — 한글 포함

# ADDRESS_ROAD: 도로명(대로/로/길) + 건물번호. 건물번호가 정규식 자체에 필수라
# ("종로에서" 처럼 번호 없이 도로명만 오면 매치 안 됨) 이게 곧 자격 조건이다 —
# 앵커 조회가 따로 필요 없다. confidence는 형식 매치만으로 고정 0.5.
#
# 초안 지시서 정규식(`[가-힣]{2,10}(?:대로|로|길)\s?\d...`)은 지선도로("OO로7길"
# 처럼 로 뒤에 지선번호+길이 오는, 도로명주소 체계의 표준 명명법)를 못 받는다 —
# "성수이로7길 12번"을 "성수이로7"(7을 건물번호로 오인, "길"과 실제 건물번호
# "12" 유실)로 잘못 잘랐다. 지시서 자신의 회귀 테스트가 이 케이스를 요구해서
# `(?:\d{1,3}길)?`을 끼워 지선도로명을 통째로 도로명에 포함시키도록 고쳤다.
ADDRESS_ROAD_PATTERN: re.Pattern[str] = re.compile(
    _KL
    + r"[가-힣]{2,10}(?:대로|로)(?:\d{1,3}길)?\s?\d{1,5}(?:-\d{1,5})?"
    + _R
    + r"|"
    + _KL
    + r"[가-힣]{2,10}길\s?\d{1,5}(?:-\d{1,5})?"
    + _R
)

# ADDRESS_LOT: 지번. "번지"/"산"이 정규식에 그대로 박혀 있어 이 리터럴 자체가
# 자격 조건이다 — 순수 숫자-숫자(`20260830-1234` 등)는 "번지"가 없어 애초에
# 안 걸린다(ORDER_ID 등과 형식 충돌 없음). confidence 고정 0.7.
ADDRESS_LOT_PATTERN: re.Pattern[str] = re.compile(
    _L + r"\d{1,4}(?:-\d{1,4})?\s?번지" + _R + r"|" + _KL + r"산\s?\d{1,4}(?:-\d{1,4})?" + _R
)

# ADDRESS_DETAIL: 동/호/층. "동"/"호"/"층" 자체가 자격 조건(리터럴)이라 여기도
# 별도 앵커 조회가 없다. 세 갈래(동+호/호만/층만)로 오탐 위험이 다르다 —
# "3층짜리 건물이에요" 같은 일반 서술과 "1502호"(단위 식별자로 훨씬 구체적)는
# confidence를 다르게 줘야 해서 named group으로 갈래를 구분한다(recognizers.py
# 의 find_address_detail 참고). 하나의 패턴으로 합쳐 둔 건 finditer가 앞쪽
# 갈래(동+호)를 먼저 소비하면 그 구간 안의 "호"만 다시 잡는 일이 없어서다 —
# ACCOUNT_NUMBER처럼 별도 패턴 두 개를 각각 돌리면 겹침 방지 로직이 또 필요해진다.
ADDRESS_DETAIL_PATTERN: re.Pattern[str] = re.compile(
    _KL
    + r"(?P<dongho>\d{1,4}동\s?\d{1,5}호)"
    + _R
    + r"|"
    + _KL
    + r"(?P<ho>\d{1,5}호)"
    + _R
    + r"|"
    + _KL
    + r"(?P<floor>(?:지하)?\d{1,3}층)"
    + _R
)
